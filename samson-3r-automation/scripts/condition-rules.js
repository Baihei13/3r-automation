// Match the installed system's names (not every Chinese translation is identical).
export function conditionRule(id) {
  const entry=TEXT[id];
  if(!entry)return null;
  const native=globalThis.CONFIG?.D35E;
  const name=native?.conditions?.[id]
    ?game.i18n.localize(native.conditions[id]):id==="disabled"?"失能":entry[0];
  return {id,ids:[id],name,img:native?.conditionTextures?.[id]??"icons/svg/aura.svg",
    description:`<p>${entry[1]}</p>`};
}
